#: What each assurance level is called wherever a person reads it.
ASSURANCE_LABELS = {"witnessed": "Witnessed", "signed": "Signed",
                    "consistency": "Unverified", "none": "Altered",
                    "absent": "No history"}

#: What a signature does and does not establish. Said next to every badge that
#: rests on one, because "Signed" beside a name reads as identity.
#: What a personal signature establishes instead, when every entry carries one.
PERSONAL_SCOPE = ("Each entry was signed with the personal key of the person the "
                  "studio's sign-in identified, so the name on it is the signed-in "
                  "person's, as far as that sign-in can be trusted.")

SIGNATURE_SCOPE = ("A signature shows an entry was written through a holder of the "
                   "studio key - in ComfyUI, this studio's ComfyAudit server - not "
                   "which person wrote it; names are as each person declared them.")

#: When some entries carry the studio key and others a person's own.
MIXED_SCOPE = ("Entries signed with a person's own key carry the name the studio's "
               "sign-in identified, as far as that sign-in can be trusted; entries signed "
               "with the studio key show only that they were written through a holder of "
               "that key, with names as each person declared them. The notes list which "
               "entries each person signed.")


@dataclass
class Verification:
    """What a history can be relied on for, said plainly."""

    present: bool = False
    entries: int = 0
    intact: bool = False
    signed: str = "no"          # no | partly (damage) | from-entry | yes
    signed_from: int = 0         # first signed entry; earlier ones predate the key
    unsigned_entries: list[int] = field(default_factory=list)
    signatures_valid: bool | None = None
    ledger: str = "not checked"  # not checked | matches | incomplete | no record | mismatch | missing entries | rewritten | absent
    current: bool | None = None  # does the workflow still match the last entry?
    problems: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    assurance: str = "absent"    # absent | none | consistency | signed | witnessed
    assurance_detail: str = ""
    signers: dict[str, list[int]] = field(default_factory=dict)

    def as_dict(self) -> dict[str, Any]:
        return dict(self.__dict__)


def chain_shot_id(history: dict[str, Any]) -> str:
    """The shot id as sealed into the chain - the one that can be trusted."""
    entries = history.get("entries") or []
    if entries and isinstance(entries[0].get("shot"), dict):
        return str(entries[0]["shot"].get("id") or "")
    return str((history.get("shot") or {}).get("id") or "")


def _as_int(value: Any) -> int | None:
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def verify(data: dict[str, Any], keys: Keys | None = None, ledger: str = "",
           history: dict[str, Any] | None = None, *, _as_parent: bool = False,
           _depth: int = 0) -> Verification:
    """Say how far a history can be relied on, naming the first thing wrong.

    ``problems`` are damage: anything there means the record cannot be taken at
    face value. ``notes`` are true and worth saying but are not damage - the
    workflow moving on since its last entry, or a ledger that started late.
    """
    keys = keys or Keys.from_environment()
    history = history if history is not None else read(data)
    v = Verification()
    if not history:
        v.assurance_detail = ("This workflow carries no history. Nothing about who "
                              "made it or how it changed can be shown from the file.")
        return v
    v.present = True
    entries = history.get("entries") or []
    v.entries = len(entries)
    if not entries:
        v.problems.append("the history block is present but holds no entries")

    prev_hash = ""
    signed: list[int] = []
    bad_sig = False
    personal: dict[str, list[int]] = {}
    unknown_signers: set[str] = set()
    for i, e in enumerate(entries, 1):
        if not isinstance(e, dict):
            v.problems.append(f"entry {i}: is not a record")
            continue
        if e.get("seq") != i:
            v.problems.append(f"entry {i}: sequence number reads {e.get('seq')!r} - "
                              "entries have been removed, duplicated or reordered")
        if e.get("prev", "") != prev_hash:
            v.problems.append(f"entry {i}: does not follow entry {i - 1} - the chain "
                              "is broken here")
        if _entry_hash(e) != e.get("hash"):
            v.problems.append(f"entry {i}: contents no longer match their hash - "
                              "this entry was edited after it was written")
        snap = snapshot_of(entries, e)
        if not snap:
            v.problems.append(f"entry {i}: its snapshot is missing or points nowhere")
        elif sha256(canonical(snap)) != e.get("snapshot_sha256"):
            v.problems.append(f"entry {i}: snapshot was altered")
        if "key_id" in e and "sig" not in e:
            # key_id is only written when signing and sits inside the hash;
            # the signature does not, so it can be dropped without breaking
            # the chain - turning signed entries into a "pre-key" prefix.
            v.problems.append(f"entry {i}: was signed, but its signature was removed")
        if "sig" in e:
            signed.append(i)
            kid = str(e.get("key_id", ""))
            key = keys.key_for(kid)
            who = e.get("actor") if isinstance(e.get("actor"), dict) else {}
            if not key:
                # No key to check it with - never the same as checked.
                unknown_signers.add("person" if kid.startswith("person:") else "studio")
            elif kid.startswith("person:"):
                person = keys.people_names[kid]
                if who.get("id") and who["id"] != person["user"]:
                    # The key is bound to the sign-in account, not the display name.
                    v.problems.append(f"entry {i}: records the account {who['id']!r} but was "
                                      f"signed with the key of {person['user']!r}")
                elif not who.get("id") and who.get("name") != person["name"]:
                    v.problems.append(f"entry {i}: names {who.get('name')!r} "
                                      f"but was signed with {person['name']}'s key")
                else:
                    if who.get("name") != person["name"]:
                        v.notes.append(f"entry {i} names {who.get('name')!r}; the studio "
                                       f"keyring now names that account ({person['user']}) "
                                       f"{person['name']!r}")
                    personal.setdefault(person["name"], []).append(i)
            sig = e["sig"]
            if key and not (isinstance(sig, str) and hmac.compare_digest(
                    hmac.new(key, str(e.get("hash", "")).encode("utf-8"),
                             hashlib.sha256).hexdigest().encode("ascii"),
                    sig.encode("utf-8"))):
                bad_sig = True
                v.problems.append(f"entry {i}: signature does not verify with "
                                  + ("this person's key" if kid.startswith("person:")
                                     else "this studio key"))
        prev_hash = e.get("hash", "")

    v.unsigned_entries = [i for i in range(1, len(entries) + 1) if i not in signed]
    v.signed = "yes" if entries and not v.unsigned_entries else ("partly" if signed else "no")
    first_signed = min(signed) if signed else 0
    late = [i for i in v.unsigned_entries if first_signed and i > first_signed]
    if late:
        # Once a history is signed, an unsigned entry is exactly what someone
        # without the key would add - a forged approval, an attestation.
        v.problems.append(
            f"entr{'y' if len(late) == 1 else 'ies'} "
            f"{', '.join(map(str, late))} carr"
            f"{'ies' if len(late) == 1 else 'y'} no signature in an "
            "otherwise signed history - added by someone without the studio key")
    elif v.signed == "partly":
        # Tracking starts on open, so histories routinely predate the studio
        # key. The first signed entry's hash covers the chain before it, so
        # those entries cannot have changed since it was signed. That is all
        # it proves: anyone can write an unsigned history and the server signs
        # whatever it is next asked to stamp on top, so what the earlier
        # entries claim - above all a person's decision - stays unproven.
        v.signed = "from-entry"
        v.signed_from = first_signed
        v.notes.append(
            f"entr{'y 1' if first_signed == 2 else f'ies 1-{first_signed - 1}'} "
            f"{'was' if first_signed == 2 else 'were'} written before the studio key "
            f"was set and could have been written by anyone; entry {first_signed}, the "
            "first signed one, shows only that they have not changed since")
        decisions = [
            f"entry {i} ({e.get('event')}"
            + (f" by {e['actor']['name']}" if isinstance(e.get("actor"), dict)
               and e["actor"].get("name") else "") + ")"
            for i, e in enumerate(entries[:first_signed - 1], 1)
            if isinstance(e, dict) and (e.get("event") in _DECISION_EVENTS or (
                e.get("event") == "note" and (e.get("data") or {}).get("evidence")))]
        if decisions:
            v.notes.append("unsigned, so unproven: " + ", ".join(decisions))
    if signed and (keys.sign_key or keys.people):
        v.signatures_valid = not bad_sig and not unknown_signers
    if unknown_signers:
        held = " or ".join(sorted({"person": "a person's key that is not in this studio "
                                             "keyring", "studio": "the studio key, which "
                                             "this check does not hold"}[u]
                                   for u in unknown_signers))
        v.notes.append(f"some entries were signed with {held}, so their signatures could "
                       "not be verified")
    if personal:
        v.signers = {name: seqs for name, seqs in personal.items()}
        v.notes.append("signed by each person's own key, with names from the studio's "
                       "sign-in: " + "; ".join(
                           f"{name} (entr{'y' if len(seqs) == 1 else 'ies'} "
                           f"{', '.join(map(str, seqs[:6]))}{' ...' if len(seqs) > 6 else ''})"
                           for name, seqs in personal.items()))

    # The top-level shot block is a convenience copy; the chain is the record.
    shot_top = history.get("shot") or {}
    shot_chain = entries[-1].get("shot") if entries and isinstance(entries[-1], dict) else None
    if isinstance(shot_chain, dict):
        for k in ("id", "name", "project", "external_ids"):
            top, sealed = shot_top.get(k), shot_chain.get(k)
            if k == "external_ids":
                top, sealed = top or {}, sealed or {}
            if top != sealed and not (k in ("name", "project") and not top and not sealed):
                v.problems.append(f"the shot's {k.replace('_', ' ')} outside the entries "
                                  "does not match what the entries record")

    if entries and not graph._looks_like_api(data) and data:  # noqa: SLF001
        v.current = snapshot_of(entries, entries[-1]).get("graph_sha256") == graph_fingerprint(data)
        if not v.current:
            v.notes.append("the workflow has changed since the last entry - those "
                           "edits are not in the history")

    if ledger:
        _check_ledger(v, entries, chain_shot_id(history), ledger, later_ok=_as_parent)

    parent = history.get("parent")
    first = entries[0] if entries and isinstance(entries[0], dict) else {}
    parent_signed = True
    if parent is not None or first.get("event") == "forked":
        parent_signed = _check_parent(v, entries, parent, keys, ledger, _depth)

    v.intact = not v.problems
    if v.problems:
        v.assurance = "none"
        v.assurance_detail = ("The history has been altered or is incomplete. Treat "
                              "everything after the first problem below as unproven.")
    elif v.signed == "yes" and v.signatures_valid and v.ledger == "matches":
        v.assurance = "witnessed"
        v.assurance_detail = ("Chain intact, every entry signed with the studio key, "
                              "and every entry's hash matches the studio ledger kept "
                              "outside the file. " + SIGNATURE_SCOPE)
    elif v.signed == "from-entry" and v.signatures_valid:
        v.assurance = "signed"
        v.assurance_detail = (f"Chain intact and signed with the studio key from entry "
                              f"{first_signed} on, so nobody without that key wrote or "
                              "changed anything since. Earlier entries predate the key: "
                              "they have not changed since then, but anyone could have "
                              "written them, so what they record is unproven. "
                              + SIGNATURE_SCOPE)
    elif v.signed == "yes" and v.signatures_valid:
        v.assurance = "signed"
        v.assurance_detail = ("Chain intact and every entry signed with the studio key, "
                              "so nobody without that key wrote or changed them. "
                              + ("Not fully matched against a ledger, so a history cut "
                                 "short at the end would not be detected. "
                                 if v.ledger != "matches" else "") + SIGNATURE_SCOPE)
    else:
        v.assurance = "consistency"
        v.assurance_detail = ("Chain intact, but " + (
            "not signed" if v.signed == "no" else
            ("the signatures could not be checked without the studio key"
             if unknown_signers <= {"studio"} else
             "some signatures could not be checked without the keys they were made "
             "with")) +
            ". That catches accidental damage and casual edits; it would not stop "
            "someone who deliberately rebuilt the chain.")
    if v.assurance in ("signed", "witnessed") and not parent_signed:
        # A fork's own entries can all be signed while the record it carries
        # was written by anyone: an unsigned history with a forged approval,
        # copied once through ComfyUI, would otherwise read as signed whole.
        # The parent is the record's prefix, so it is treated like one.
        v.signed, v.signed_from, v.assurance = "from-entry", 1, "signed"
        v.assurance_detail = ("This record's own entries are signed with the studio key, "
                              "so nobody without that key wrote or changed them. The "
                              "parent record it was forked from is not signed throughout: "
                              "it has not changed since the fork, but what it records is "
                              "unproven. " + SIGNATURE_SCOPE)
    if personal and v.assurance in ("signed", "witnessed"):
        if sum(len(x) for x in personal.values()) == len(signed):
            kind, scope = "with personal keys", PERSONAL_SCOPE
        else:
            # Studio-key entries carry names as declared; only personal ones
            # carry the sign-in's name. Say both, and which is which.
            kind, scope = "with the studio key or a person's own key", MIXED_SCOPE
        v.assurance_detail = (v.assurance_detail.replace("with the studio key", kind)
                              .replace("without that key", "without those keys")
                              .replace(SIGNATURE_SCOPE, scope))
    return v


#: How deep forks of forks may nest. Far beyond any real version history,
#: and well inside what verify's recursion and the JSON encoder can take.
MAX_FORK_DEPTH = 64


def fork_depth(history: dict[str, Any] | None) -> int:
    """How many parents a record carries, nested one inside the next."""
    depth, h = 0, history
    while isinstance(h, dict) and isinstance(h.get("parent"), dict) and depth <= MAX_FORK_DEPTH:
        h = h["parent"].get("history")
        depth += 1
    return depth


def _check_parent(v: Verification, entries: list[dict[str, Any]], parent: Any,
                  keys: Keys, ledger: str, depth: int) -> bool:
    """A forked record carries its parent frozen; both must hold, and agree.

    The parent is checked against the ledger as an old copy: the shot carried
    on after the fork, so later entries there are expected, but different
    contents for an entry the parent has are a rewrite. Returns whether the
    parent is signed throughout, which the record as a whole can be no more
    than.
    """
    first = entries[0] if entries and isinstance(entries[0], dict) else {}
    link = (first.get("data") or {}).get("parent") or {}
    phist = parent.get("history") if isinstance(parent, dict) else None
    if first.get("event") == "forked" and parent is None:
        v.problems.append("the record begins with a fork from another record, but that "
                          "record has been removed from the file")
        return False
    if first.get("event") != "forked" or not isinstance(phist, dict):
        v.problems.append("the record names a parent but does not begin with the fork from it")
        return False
    if depth >= MAX_FORK_DEPTH:
        v.problems.append(f"the record's parents are nested more than {MAX_FORK_DEPTH} "
                          "deep, past what can be checked")
        return False
    pentries = phist.get("entries") or []
    if (not pentries or not isinstance(pentries[-1], dict)
            or link.get("head") != pentries[-1].get("hash")
            or link.get("shot") != chain_shot_id(phist)):
        v.problems.append("the parent record carried in this file is not the one the "
                          "fork was made from")
    pv = verify({}, keys=keys, ledger=ledger, history=phist, _as_parent=True,
                _depth=depth + 1)
    for problem in pv.problems:
        v.problems.append(f"the parent record: {problem}")
    if pv.assurance not in ("none", "absent"):
        v.notes.append(f"forked from {link.get('name') or 'another record'} at its entry "
                       f"{link.get('seq')}; the parent record is "
                       f"{ASSURANCE_LABELS.get(pv.assurance, pv.assurance).lower()}")
    whole = pv.assurance in ("signed", "witnessed") and pv.signed == "yes"
    if not whole and pv.assurance not in ("none", "absent"):
        v.notes.append("the parent record is not signed throughout, so what it records "
                       "- above all any decision in it - is unproven")
    return whole


def _check_ledger(v: Verification, entries: list[dict[str, Any]], shot_id: str,
                  ledger: str, *, later_ok: bool = False) -> None:
    if not os.path.exists(ledger):
        v.ledger = "absent"
        v.notes.append("the ledger file named for this check does not exist")
        return
    seen: dict[int, set[str]] = {}
    for row in _ledger_rows(ledger, shot_id):
        seq = _as_int(row.get("seq"))
        if seq is None or not isinstance(row.get("hash"), str):
            continue
        seen.setdefault(seq, set()).add(row["hash"])
    if not seen:
        v.ledger = "no record"
        v.notes.append("the ledger has no record of this shot, so it cannot "
                       "confirm or contradict the history")
        return
    rewritten = sorted(s for s, hs in seen.items() if len(hs) > 1)
    mismatched = sorted(s for s, hs in seen.items()
                        if len(hs) == 1 and s <= len(entries)
                        and entries[s - 1].get("hash") not in hs)
    beyond = sorted(s for s in seen if s > len(entries))
    unwitnessed = [i for i in range(1, len(entries) + 1) if i not in seen]
    # Checked mildest first, so the ledger label ends on the most serious finding.
    if beyond and later_ok:
        # An old copy (a fork's parent, an earlier render's sidecar): the
        # shot went on after it, so the ledger rightly holds more.
        v.notes.append("the ledger shows the shot carried on after this copy")
    elif beyond:
        v.ledger = "missing entries"
        v.problems.append(f"the ledger has {len(beyond)} later entr"
                          f"{'y' if len(beyond) == 1 else 'ies'} that this file "
                          "does not - the history has been cut short")
    if mismatched:
        v.ledger = "mismatch"
        v.problems.append(f"the ledger disagrees with entr{'y' if len(mismatched) == 1 else 'ies'} "
                          f"{', '.join(map(str, mismatched))} - the history was replaced "
                          "or rewritten")
    if rewritten:
        v.ledger = "rewritten"
        v.problems.append(f"the ledger recorded different contents for entr"
                          f"{'y' if len(rewritten) == 1 else 'ies'} "
                          f"{', '.join(map(str, rewritten))} at different times - "
                          "the history was rewritten after it was written")
    if not (rewritten or mismatched or (beyond and not later_ok)):
        if unwitnessed:
            v.ledger = "incomplete"
            v.notes.append(f"entr{'y' if len(unwitnessed) == 1 else 'ies'} "
                           f"{', '.join(map(str, unwitnessed[:8]))}"
                           f"{' and more' if len(unwitnessed) > 8 else ''} "
                           "are not in the ledger, so the ledger cannot vouch for them")
        else:
            v.ledger = "matches"


# ---------------------------------------------------------------------------
# the lifetime view: what a report needs
# ---------------------------------------------------------------------------

def lineage(history: dict[str, Any]) -> dict[str, Any]:
    """Distil the chain into the lifetime story a legal reviewer reads."""
    entries = history.get("entries", [])
    people: list[dict[str, Any]] = []
    seen: dict[str, dict[str, Any]] = {}
    models: dict[str, dict[str, Any]] = {}
    prompts: dict[str, dict[str, Any]] = {}
    sources: dict[str, dict[str, Any]] = {}
    stages: list[dict[str, Any]] = []
    breakpoints: dict[str, int] = {}
    renders = 0
    param_changes = 0
    unsupervised_runs = 0
    streak = 0

    for e in entries:
        who = e["actor"].get("name") or "unknown"
        p = seen.get(who)
        if p is None:
            p = {"name": who, "role": e["actor"].get("role", ""),
                 "first": e["at"], "last": e["at"], "entries": 0, "events": {}}
            seen[who] = p
            people.append(p)
        p["last"] = e["at"]
        p["entries"] += 1
        p["events"][e["event"]] = p["events"].get(e["event"], 0) + 1
        snap = snapshot_of(entries, e)

        for m in snap.get("models", []):
            k = _model_key(m)
            rec = models.setdefault(k, {"filename": m["filename"], "folder": m["folder"],
                                        "role": m.get("role", ""),
                                        "licence": m["licence"],
                                        "commercial_use": m["commercial_use"],
                                        "introduced": e["seq"], "introduced_by": who,
                                        "removed": None, "removed_by": "",
                                        "in_final": False})
            rec["licence"] = m["licence"]
            rec["commercial_use"] = m["commercial_use"]
            rec["enabled"] = m.get("enabled", True)
            rec["conflict"] = m.get("conflict", "")
            if rec["removed"] is not None:
                rec["removed"], rec["removed_by"] = None, ""
        current = {_model_key(m) for m in snap.get("models", [])}
        for k, rec in models.items():
            if k not in current and rec["removed"] is None:
                rec["removed"], rec["removed_by"] = e["seq"], who

        # A prompt belongs to whoever first wrote that exact text into the
        # graph - the ownership question in a sentence. Keyed by fingerprint,
        # so it holds even when the text itself is encrypted or redacted.
        for pr in snap.get("prompts", []):
            pre = e["event"] == "imported"
            rec = prompts.setdefault(pr["sha256"], {
                "sha256": pr["sha256"], "node": pr["node"], "polarity": pr["polarity"],
                "text": pr.get("text"), "protected": "text" not in pr,
                # Text already in a graph when tracking began was written by
                # someone the record never saw.
                "authored_by": "before tracking" if pre else who,
                "authored_at": e["at"], "first_seq": e["seq"], "pre_existing": pre,
                "renders": 0, "in_final": False})
        if e["event"] == "rendered":
            for pr in snap.get("prompts", []):
                if pr.get("enabled", True) and pr["sha256"] in prompts:
                    prompts[pr["sha256"]]["renders"] += 1

        for inp in snap.get("inputs", []):
            if not (inp.get("upload") or inp.get("kind") in SOURCE_KINDS):
                continue
            rec = sources.setdefault(inp["node"], {
                "node": inp["node"], "kind": inp["kind"], "sha256": inp["sha256"],
                "value": inp.get("text"), "origin": "", "asset_id": "", "owner": "",
                "declared_by": "", "note": "", "first_seq": e["seq"]})
            if rec["sha256"] != inp["sha256"]:
                # A different file in the same slot is a different source; an
                # earlier declaration does not carry over to it.
                rec.update({"sha256": inp["sha256"], "value": inp.get("text"),
                            "origin": "", "asset_id": "", "owner": "",
                            "declared_by": "", "note": ""})
            picked = next((x for x in (e.get("changes") or {}).get("selected", [])
                           if x.get("node") == inp["node"]), None)
            if picked and not rec.get("origin"):
                # Its contents match a render this history recorded, so where
                # it came from is known without anyone having to say so.
                rec.update({"origin": "generated", "declared_by": "recorded automatically",
                            "note": f"output of entry {picked['from_entry']}",
                            "from_entry": picked["from_entry"]})
        if e["event"] == "sourced":
            d = e.get("data", {})
            rec = sources.setdefault(str(d.get("node")), {
                "node": str(d.get("node")), "kind": "", "sha256": "", "value": None,
                "first_seq": e["seq"]})
            rec.update({"origin": d.get("origin", "unknown"),
                        "asset_id": d.get("asset_id", ""), "owner": d.get("owner", ""),
                        "declared_by": who, "note": e.get("note", "")})

        if e["event"] == "promoted":
            stages.append({"stage": e["data"].get("stage"), "from": e["data"].get("from"),
                           "by": who, "at": e["at"], "seq": e["seq"],
                           "note": e.get("note", "")})

        param_changes += len(e.get("changes", {}).get("params_changed", [])) \
            + len(e.get("changes", {}).get("seeds_changed", []))

        for kind in e.get("breakpoints", []):
            breakpoints[kind] = breakpoints.get(kind, 0) + 1

        if e["event"] == "rendered":
            renders += 1
            streak = 1 if e.get("breakpoints") else streak + 1
            if streak > 1:
                unsupervised_runs += 1
        elif e["event"] in HUMAN_EVENTS and e.get("breakpoints"):
            streak = 0

    final_render = next((e for e in reversed(entries) if e["event"] == "rendered"), None)
    basis = final_render or (entries[-1] if entries else None)
    basis_snap = snapshot_of(entries, basis) if basis else {"models": [], "prompts": []}
    # A bypassed or muted model is in the file but never touched the pixels.
    # For a licence question that difference is the whole answer.
    final_models = {_model_key(m) for m in basis_snap["models"] if m.get("enabled", True)}
    for k, rec in models.items():
        rec["in_final"] = k in final_models
    final_prompts = {pr["sha256"] for pr in basis_snap["prompts"] if pr.get("enabled", True)}
    for h, rec in prompts.items():
        rec["in_final"] = h in final_prompts

    after_final = [e for e in entries if final_render and e["seq"] > final_render["seq"]]
    reviewed_final = any(e["event"] in ("reviewed", "approved", "rejected")
                         for e in after_final)
    last_approval = next((e for e in reversed(entries) if e["event"] == "approved"), None)
    later_rejection = last_approval is not None and any(
        e["event"] == "rejected" and e["seq"] > last_approval["seq"] for e in entries)
    # A sign-off covers the output it was given on. One that predates the final
    # render, or was followed by a rejection, does not cover what shipped.
    approved = last_approval if (
        last_approval is not None and not later_rejection
        and (final_render is None or last_approval["seq"] > final_render["seq"])) else None
    stage = stages[-1]["stage"] if stages else "sandbox"

    human_steps = sum(1 for e in entries if e.get("breakpoints"))

    gaps: list[str] = []
    if entries and entries[0]["event"] == "imported":
        gaps.append(f"Tracking began on {entries[0]['at'][:10]}; anything before that "
                    "is not recorded.")
    if not (entries and entries[-1].get("shot", {}).get("external_ids")):
        gaps.append("Not linked to a studio asset ID (ShotGrid, Sparky, ftrack). "
                    "Provenance should start where the asset was born, not where "
                    "ComfyUI first saw it.")
    undeclared = [s["node"] for s in sources.values()
                  if not s.get("origin") or s.get("origin") == "unknown"]
    if undeclared:
        gaps.append(f"{len(undeclared)} source input(s) have no known origin "
                    f"(node {', '.join(undeclared)}). Legal will ask where each came from.")
    if last_approval is not None and approved is None:
        gaps.append(f"The sign-off at entry {last_approval['seq']} does not cover the "
                    "current output: " + ("it was followed by a rejection."
                                          if later_rejection else
                                          "a later render replaced what was approved."))
    if renders and not reviewed_final:
        gaps.append("No person is recorded reviewing the final render. Record a review "
                    "or approval so the human decision on the delivered output is on file.")
    if unsupervised_runs:
        gaps.append(f"{unsupervised_runs} render(s) followed another render with no "
                    "recorded human step in between.")
    human_made = [s for s in sources.values() if s.get("origin") in HUMAN_ORIGINS]
    if not human_made:
        gaps.append("No human-made source material is recorded (an artist's plate, "
                    "drawing, paintover or layout). Prompts and selections document the "
                    "process, but copyright offices and courts treat prompts alone as "
                    "insufficient for authorship; human material that remains visible in "
                    "the output, and human edits after generation, carry more weight.")
    if any(p.get("pre_existing") for p in prompts.values()):
        gaps.append("Some prompts were already in the graph when tracking began; who "
                    "wrote them is not recorded.")
    if stage == "sandbox" and approved:
        gaps.append("An output was approved while the shot is still marked sandbox. "
                    "Promote it to production so the clearance trail starts at the "
                    "right point.")
    anon = [p["name"] for p in people if p["name"] in ("unknown", "", "root")]
    if anon:
        gaps.append("Some entries have no meaningful name attached. Set a user name in "
                    "the ComfyAudit settings so each change is attributable.")

    # The chain is the authority on what this shot is; the top-level block is a
    # convenience copy that nothing protects.
    top = history.get("shot", {}) or {}
    if entries and isinstance(entries[-1].get("shot"), dict):
        sealed = entries[-1]["shot"]
        shot = {"id": sealed.get("id", ""), "name": sealed.get("name", ""),
                "project": sealed.get("project", ""),
                "external_ids": dict(sealed.get("external_ids") or {}),
                "started": entries[0].get("at", "")}
    else:
        shot = {"id": top.get("id", ""), "name": top.get("name", ""),
                "project": top.get("project", ""), "external_ids": {},
                "started": top.get("started", "")}
    shot["stage"] = stage
    if entries and entries[0].get("event") == "forked":
        link = (entries[0].get("data") or {}).get("parent") or {}
        shot["parent"] = {**link, "reason": (entries[0].get("data") or {}).get("reason", "")}

    return {
        "shot": shot,
        "entries": len(entries),
        "people": people,
        "models": sorted(models.values(), key=lambda r: (r["introduced"], r["filename"])),
        "prompts": sorted(prompts.values(), key=lambda r: r["first_seq"]),
        "sources": sorted(sources.values(), key=lambda r: str(r["node"])),
        "stages": stages,
        "breakpoints": breakpoints,
        "human_steps": human_steps,
        "machine_steps": renders,
        "renders": renders,
        "iterations": {"renders": renders, "setting_changes": param_changes,
                       "prompt_versions": len(prompts)},
        "final_render": final_render["seq"] if final_render else None,
        "final_outputs": final_render.get("outputs", []) if final_render else [],
        "final_reviewed": reviewed_final,
        "approved": ({"seq": approved["seq"], "by": approved["actor"].get("name", ""),
                      "role": approved["actor"].get("role", ""),
                      "at": approved["at"], "note": approved.get("note", "")}
                     if approved else None),
        "gaps": gaps,
    }


def timeline(history: dict[str, Any], keys: Keys | None = None,
             reveal: bool = False) -> list[dict[str, Any]]:
    """Entries trimmed for display. Prompts are revealed only when asked."""
    keys = keys or Keys()
    rows = []
    entries = history.get("entries", [])
    for e in entries:
        snap = snapshot_of(entries, e)
        prompts = []
        for p in snap["prompts"]:
            text = unseal(p, keys) if reveal else p.get("text")
            prompts.append({"node": p["node"], "polarity": p["polarity"],
                            "sha256": p["sha256"],
                            "text": text if text is not None else None,
                            "protected": "text" not in p})
        rows.append({
            "seq": e["seq"], "at": e["at"], "event": e["event"],
            "label": EVENTS.get(e["event"], e["event"]),
            "actor": e["actor"], "note": e.get("note", ""),
            "changes": e.get("changes", {}),
            "breakpoints": e.get("breakpoints", []),
            "models": [m["filename"] for m in snap["models"] if m.get("enabled", True)],
            "unchanged": "snapshot" not in e,
            "prompts": prompts,
            "outputs": e.get("outputs", []),
            "hash": e["hash"], "signed": "sig" in e,
        })
    return rows


