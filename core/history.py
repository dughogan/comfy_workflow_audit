def witness(ledger_path: str, history: dict[str, Any], entry: dict[str, Any]) -> None:
    """Append the new head to an append-only JSONL ledger the studio keeps.

    The chain inside the file proves the entries agree with each other. It
    cannot prove none were dropped from the end, or that the whole history was
    not swapped for a cleaner one. A copy of each head hash kept somewhere the
    workflow does not travel closes both gaps.
    """
    os.makedirs(os.path.dirname(os.path.abspath(ledger_path)), exist_ok=True)
    row = {"shot": history["shot"]["id"], "name": history["shot"].get("name", ""),
           "seq": entry["seq"], "hash": entry["hash"], "at": entry["at"],
           "event": entry["event"], "actor": entry["actor"].get("name", "")}
    with open(ledger_path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(row, sort_keys=True) + "\n")


def _ledger_rows(ledger_path: str, shot_id: str) -> list[dict[str, Any]]:
    rows = []
    with open(ledger_path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except ValueError:
                continue
            if row.get("shot") == shot_id:
                rows.append(row)
    return rows


