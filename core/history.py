def graph_fingerprint(data: dict[str, Any]) -> str:
    """Hash of the workflow's substance - not its layout, not its history.

    Moving a node, resizing a group or panning the canvas is not a change
    anyone needs to defend, so positions, sizes, colours and the history block
    itself are left out. Node types, widget values, modes and wiring are in.
    """
    doc = copy.deepcopy(data)
    if graph._looks_like_api(doc):  # noqa: SLF001 - same package
        doc.pop("_comfyaudit_history", None)
        return sha256(canonical(doc))

    def strip(g: dict[str, Any]) -> dict[str, Any]:
        nodes = []
        for n in g.get("nodes", []) or []:
            nodes.append({"id": n.get("id"), "type": n.get("type"),
                          "mode": n.get("mode", 0),
                          "widgets_values": n.get("widgets_values"),
                          "inputs": [(i.get("name"), i.get("link"))
                                     for i in n.get("inputs") or []]})
        links = [list(l)[:6] if isinstance(l, list) else
                 [l.get(k) for k in ("id", "origin_id", "origin_slot",
                                     "target_id", "target_slot", "type")]
                 for l in g.get("links", []) or []]
        return {"nodes": sorted(nodes, key=lambda n: str(n["id"])),
                "links": sorted(links, key=lambda l: str(l[0]))}

    body = strip(doc)
    subs = (doc.get("definitions") or {}).get("subgraphs") or []
    body["subgraphs"] = [strip(s) for s in subs]
    return sha256(canonical(body))


def snapshot(data: dict[str, Any], keys: Keys | None = None,
             matcher: licences_mod.LicenceMatcher | None = None) -> dict[str, Any]:
    """Everything a legal review needs to know about the workflow right now."""
    keys = keys or Keys()
    wf = graph.from_dict(copy.deepcopy(data))
    matcher = matcher or licences_mod.LicenceMatcher()

    prompts, _notes = prompts_extract.extract(wf)
    raw_models = models_extract.extract(wf)
    in_graph = {m.filename for m in raw_models}
    from_prompts: set[str] = set()
    for p in prompts:
        extra = (models_extract.from_prompt_embeddings(p.embeddings, p)
                 + models_extract.from_prompt_loras(p.inline_loras, p))
        from_prompts.update(m.filename for m in extra)
        raw_models.extend(extra)
    models = models_extract.deduplicate(raw_models)
    # A LoRA or embedding named only inside a protected prompt is part of that
    # prompt's text; listing it in the clear would leak what the prompt hides.
    hidden = (from_prompts - in_graph) if keys.confidentiality != "none" else set()
    inputs, outputs = assets_extract.extract(wf)
    packs, core_types, api_types = packs_extract.extract(wf)

    model_rows = []
    for m in sorted(models, key=lambda m: (m.folder, m.filename.lower())):
        lic = matcher.for_model(m)
        name = m.filename
        if name in hidden:
            name = "protected:" + fingerprint(name, keys).split(":")[-1][:16]
        model_rows.append({
            "filename": name, "folder": m.folder, "role": m.role,
            "node": str(m.node_id), "enabled": m.enabled,
            "strength": m.strength,
            "licence": lic.name, "commercial_use": lic.commercial_use,
        })

    prompt_rows = []
    for p in sorted(prompts, key=lambda p: (str(p.node_id), p.widget)):
        if p.driven_by_link or not p.text.strip():
            continue
        prompt_rows.append({"node": str(p.node_id), "polarity": p.polarity,
                            "enabled": p.enabled, **_seal(p.text, keys)})

    input_rows = []
    for a in inputs:
        row = {"node": str(a.node_id), "kind": a.kind, "upload": a.upload_widget}
        row.update(_seal(str(a.value), keys))
        input_rows.append(row)

    params: dict[str, dict[str, Any]] = {}
    seeds: dict[str, Any] = {}
    modes: dict[str, str] = {}
    for node in wf:
        picked = {k: v for k, v in node.widgets.items() if k in _PARAM_WIDGETS
                  and isinstance(v, (int, float, str, bool))}
        if picked:
            params[node.id] = picked
        for k in _SEED_WIDGETS & set(node.widgets):
            seeds[node.id] = node.widgets[k]
        if not node.enabled:
            modes[node.id] = node.mode_name

    custom = []
    for pack in packs:
        custom.append({"pack": pack.title or pack.repo or pack.registry_id or "unidentified",
                       "version": pack.pinned_version or "",
                       "nodes": sorted(set(pack.node_types))})

    return {
        "graph_sha256": graph_fingerprint(data),
        "node_count": len(wf),
        "models": model_rows,
        "prompts": prompt_rows,
        "inputs": input_rows,
        "outputs": sorted({str(o.node_id) for o in outputs}),
        "nodes": {
            "core": sorted(set(core_types)),
            "api": sorted(set(api_types)),
            "custom": sorted(custom, key=lambda c: c["pack"]),
        },
        "params": params,
        "seeds": seeds,
        "bypassed": modes,
        "comfyui_catalog": catalog.comfyui_version(),
    }


