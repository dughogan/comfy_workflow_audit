"""Shot history: a tamper-evident record of a workflow's whole life, kept inside it.

A licence audit answers *what is in this workflow now*. Legal teams on a
commercial job get asked a different question, months later: *how did this
frame come to exist?* Who built the graph, who changed it, which models came and
went, which prompts produced the delivered pixels, and where a person - rather
than a model - made the decisions.

Most of that is already sitting in the workflow JSON at any one moment. What a
workflow does not keep is its past: every save overwrites it. So the history is
a chain of *snapshots*, appended whenever the substance of the graph changes,
and carried inside the workflow itself under ``extra.comfyaudit_history``. It
travels wherever the file goes, including into the PNG metadata of every image
ComfyUI renders from it.

Three properties make it worth showing to a lawyer:

* **Tamper-evident.** Every entry hashes the one before it. Editing, removing
  or reordering an entry breaks the chain at that point, and ``verify`` says
  exactly where.
* **Signed, when the studio has a key.** A hash chain alone stops accidents,
  not forgers: someone determined can recompute every hash. With
  ``COMFYAUDIT_HISTORY_KEY`` set, each entry also carries an HMAC that only a
  holder of the studio key can produce. An optional append-only *ledger* file
  outside the workflow records each head hash, so a history that has been cut
  short or swapped wholesale no longer matches the ledger.
* **Confidential, when it needs to be.** Prompts are often the client's
  creative. They can be encrypted (AES-256-GCM, needs the ``cryptography``
  package) or redacted to a SHA-256 fingerprint, which still proves *which*
  prompt was used without revealing it. Models, nodes and licences stay
  readable either way: that is what the legal review is about.

Identity is recorded as the person declared it (settings, environment, or the
OS account). The signature proves the entry came from someone holding the
studio key - not which person that was. Per-person keys (``key_id``) narrow it;
the report states plainly which level of assurance a history actually has.

Nothing here contacts the network.
"""

