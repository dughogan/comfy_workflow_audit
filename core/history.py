def _model_key(m: dict[str, Any]) -> str:
    return f"{m['folder']}/{m['filename']}".lower()


def diff(before: dict[str, Any] | None, after: dict[str, Any]) -> dict[str, Any]:
    """The substantive difference, in terms a reviewer would use."""
    if not before:
        return {"initial": True,
                "models_added": [m["filename"] for m in after["models"]],
                "prompts_added": [p["node"] for p in after["prompts"]]}
    out: dict[str, Any] = {}

    b_models = {_model_key(m): m for m in before["models"]}
    a_models = {_model_key(m): m for m in after["models"]}
    added = [a_models[k] for k in a_models.keys() - b_models.keys()]
    removed = [b_models[k] for k in b_models.keys() - a_models.keys()]
    if added:
        out["models_added"] = sorted(m["filename"] for m in added)
    if removed:
        out["models_removed"] = sorted(m["filename"] for m in removed)
    strength = [f"{a_models[k]['filename']}: {b_models[k].get('strength')} -> {a_models[k].get('strength')}"
                for k in a_models.keys() & b_models.keys()
                if a_models[k].get("strength") != b_models[k].get("strength")]
    if strength:
        out["model_strength_changed"] = sorted(strength)
    off = sorted(a_models[k]["filename"] for k in a_models.keys() & b_models.keys()
                 if b_models[k].get("enabled", True) and not a_models[k].get("enabled", True))
    on = sorted(a_models[k]["filename"] for k in a_models.keys() & b_models.keys()
                if not b_models[k].get("enabled", True) and a_models[k].get("enabled", True))
    if off:
        out["models_disabled"] = off
    if on:
        out["models_enabled"] = on
    lic = [f"{a_models[k]['filename']}: {b_models[k]['licence']} -> {a_models[k]['licence']}"
           for k in a_models.keys() & b_models.keys()
           if a_models[k]["licence"] != b_models[k]["licence"]]
    if lic:
        out["licence_changed"] = sorted(lic)

    def keyed(rows, key):
        return {(r["node"], r.get(key, "")): r for r in rows}

    bp = {(p["node"], p["polarity"]): p["sha256"] for p in before["prompts"]}
    ap = {(p["node"], p["polarity"]): p["sha256"] for p in after["prompts"]}
    changed = [f"{n} ({pol})" for (n, pol), h in ap.items() if (n, pol) in bp and bp[(n, pol)] != h]
    new = [f"{n} ({pol})" for (n, pol) in ap.keys() - bp.keys()]
    gone = [f"{n} ({pol})" for (n, pol) in bp.keys() - ap.keys()]
    if changed:
        out["prompts_changed"] = sorted(changed)
    if new:
        out["prompts_added"] = sorted(new)
    if gone:
        out["prompts_removed"] = sorted(gone)

    bi = {i["node"]: i["sha256"] for i in before["inputs"]}
    ai = {i["node"]: i["sha256"] for i in after["inputs"]}
    media = sorted(n for n in ai if bi.get(n) != ai[n])
    if media:
        out["inputs_changed"] = media

    bc = {c["pack"]: c for c in before["nodes"]["custom"]}
    ac = {c["pack"]: c for c in after["nodes"]["custom"]}
    if ac.keys() - bc.keys():
        out["packs_added"] = sorted(ac.keys() - bc.keys())
    if bc.keys() - ac.keys():
        out["packs_removed"] = sorted(bc.keys() - ac.keys())
    ver = [f"{p}: {bc[p]['version'] or 'unpinned'} -> {ac[p]['version'] or 'unpinned'}"
           for p in ac.keys() & bc.keys() if ac[p]["version"] != bc[p]["version"]]
    if ver:
        out["pack_versions_changed"] = sorted(ver)
    for kind in ("core", "api"):
        plus = sorted(set(after["nodes"][kind]) - set(before["nodes"][kind]))
        minus = sorted(set(before["nodes"][kind]) - set(after["nodes"][kind]))
        if plus:
            out[f"{kind}_nodes_added"] = plus
        if minus:
            out[f"{kind}_nodes_removed"] = minus

    moved = [n for n in after["seeds"] if before["seeds"].get(n) != after["seeds"][n]]
    auto = {n for n in moved if str(after["params"].get(n, {}).get("control_after_generate", ""))
            in ("randomize", "increment", "decrement")}
    if set(moved) - auto:
        out["seeds_changed"] = sorted(set(moved) - auto)
    if auto:
        # The sampler advanced these itself after a queue; nobody chose them.
        out["seeds_advanced"] = sorted(auto)
    params = []
    for n, vals in after["params"].items():
        old = before["params"].get(n, {})
        for k, v in vals.items():
            if k in _SEED_WIDGETS or k == "control_after_generate":
                continue
            if old.get(k) != v:
                params.append(f"{n}.{k}: {old.get(k)} -> {v}")
    if params:
        out["params_changed"] = sorted(params)
    toggled = sorted(set(before["bypassed"].items()) ^ set(after["bypassed"].items()))
    if toggled:
        out["branches_toggled"] = sorted({n for n, _ in toggled})
    if before["node_count"] != after["node_count"]:
        out["node_count"] = f"{before['node_count']} -> {after['node_count']}"
    return out


def breakpoints_for(event: str, changes: dict[str, Any], note: str = "",
                    handoff: bool = False) -> list[str]:
    """Which kinds of human decision this entry records.

    Deliberately conservative, because these rows are what a reader takes as
    evidence of a person directing the work:

    * Taking an existing graph under tracking records nothing as authored by
      the importer - its contents predate the record.
    * A note counts only when it says something.
    * A render that arrives carrying graph changes (someone edited, then queued
      without an intermediate save) records those changes as the person's;
      seeds a sampler advanced on its own never count.
    """
    kinds: list[str] = []
    if event == "imported":
        return []
    if event == "created":
        kinds.append("authored")
    if event in ("edited", "rendered") and (
            changes.get("node_count") or changes.get("core_nodes_added")
            or changes.get("packs_added") or changes.get("api_nodes_added")):
        kinds.append("authored")
    if event in HUMAN_EVENTS or event == "rendered":
        if changes.get("prompts_changed") or changes.get("prompts_added"):
            kinds.append("prompt")
        if changes.get("inputs_changed"):
            kinds.append("source-media")
        if changes.get("models_added") or changes.get("models_removed") \
                or changes.get("model_strength_changed") or changes.get("models_disabled") \
                or changes.get("models_enabled"):
            kinds.append("model-choice")
        if changes.get("branches_toggled"):
            kinds.append("branch")
        if changes.get("params_changed"):
            kinds.append("parameters")
        if changes.get("seeds_changed"):
            kinds.append("seed")
        # A render brought back in as an input is a person choosing it.
        if changes.get("selected"):
            kinds.append("selection")
        # The next person to change the shot has taken it over.
        if handoff:
            kinds.append("handoff")
    if event == "reviewed":
        kinds.append("review")
    if event in ("approved", "rejected"):
        kinds.append("selection")
    if event == "handoff":
        kinds.append("handoff")
    if event == "note" and note.strip():
        kinds.append("note")
    if event == "sourced":
        kinds.append("sourcing")
    if event == "promoted":
        kinds.append("stage")
    seen: list[str] = []
    for k in kinds:
        if k not in seen:
            seen.append(k)
    return seen


