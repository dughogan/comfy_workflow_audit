def canonical(obj: Any) -> bytes:
    """Deterministic JSON bytes: the thing every hash is taken over."""
    return json.dumps(obj, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False, default=str).encode("utf-8")


def sha256(data: bytes | str) -> str:
    if isinstance(data, str):
        data = data.encode("utf-8")
    return hashlib.sha256(data).hexdigest()


def now() -> str:
    return _dt.datetime.now().astimezone().isoformat(timespec="seconds")


@dataclass
class Actor:
    """Who did it, as declared. See the module docstring on what that proves."""

    name: str = ""
    id: str = ""
    role: str = ""
    machine: str = ""
    tool: str = ""
    declared_by: str = ""     # settings | environment | os-account | explicit

    @classmethod
    def current(cls, name: str = "", role: str = "", tool: str = "") -> "Actor":
        if name:
            source = "explicit"
        elif os.environ.get("COMFYAUDIT_USER"):
            name, source = os.environ["COMFYAUDIT_USER"], "environment"
        else:
            try:
                name = getpass.getuser()
            except Exception:  # noqa: BLE001 - containers without a passwd entry
                name = "unknown"
            source = "os-account"
        try:
            machine = socket.gethostname()
        except OSError:
            machine = platform.node()
        return cls(name=name, id=os.environ.get("COMFYAUDIT_USER_ID", ""),
                   role=role or os.environ.get("COMFYAUDIT_ROLE", ""),
                   machine=machine,
                   tool=tool or f"comfyaudit {__version__}",
                   declared_by=source)

    def as_dict(self) -> dict[str, Any]:
        return {k: v for k, v in self.__dict__.items() if v}


