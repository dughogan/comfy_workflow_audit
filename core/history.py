@dataclass
class Keys:
    """Studio secrets. Both optional; each buys one specific guarantee."""

    sign_key: bytes = b""
    key_id: str = ""
    enc_key: bytes = b""
    #: ``none`` | ``encrypt`` | ``redact`` - what happens to prompt text and
    #: source-media paths inside snapshots.
    confidentiality: str = "none"
    #: Personal signing keys by key id (``person:<user>:<fingerprint>``), and
    #: the name and role each belongs to, from the studio keyring.
    people: dict[str, bytes] = field(default_factory=dict)
    people_names: dict[str, dict[str, str]] = field(default_factory=dict)
    #: While signing as one person, the studio key kept apart for checking
    #: entries signed before the switch to personal keys. None otherwise.
    studio_key: bytes | None = None

    def for_person(self, user: str) -> "Keys | None":
        """These keys, signing as one person from the keyring; None if unknown."""
        for kid, info in self.people_names.items():
            if info.get("user") == user:
                return Keys(sign_key=self.people[kid], key_id=kid, enc_key=self.enc_key,
                            confidentiality=self.confidentiality, people=self.people,
                            people_names=self.people_names, studio_key=self.key_for(""))
        return None

    def key_for(self, key_id: str) -> bytes:
        """The key an entry says it was signed with: a person's, else the studio's."""
        if key_id.startswith("person:"):
            return self.people.get(key_id, b"")
        return self.sign_key if self.studio_key is None else self.studio_key

    @classmethod
    def from_environment(cls, confidentiality: str = "") -> "Keys":
        sign = os.environ.get("COMFYAUDIT_HISTORY_KEY", "")
        key_file = os.environ.get("COMFYAUDIT_HISTORY_KEY_FILE", "")
        if not sign and key_file and os.path.isfile(key_file):
            # The same file the server signs with, so the CLI checks what it wrote.
            with open(key_file, encoding="utf-8") as fh:
                sign = fh.read().strip()
        enc = os.environ.get("COMFYAUDIT_HISTORY_ENC_KEY", "")
        env_mode = (os.environ.get("COMFYAUDIT_HISTORY_CONFIDENTIALITY", "")
                    or ("encrypt" if enc else "none"))
        # A caller (a settings panel, a CLI flag) may tighten what the
        # environment asks for, never loosen it: the default "prompts readable"
        # in a UI must not quietly override a studio's encryption key.
        mode = strongest(confidentiality or "none", env_mode)
        people, names = load_keyring(os.environ.get("COMFYAUDIT_HISTORY_KEYRING", ""))
        return cls(people=people, people_names=names,
                   sign_key=_derive(sign, b"comfyaudit-sign") if sign else b"",
                   key_id=os.environ.get("COMFYAUDIT_HISTORY_KEY_ID", "")
                   or (sha256(_derive(sign, b"comfyaudit-sign"))[:12] if sign else ""),
                   enc_key=_derive(enc, b"comfyaudit-enc") if enc else b"",
                   confidentiality=mode)


def load_keyring(path: str) -> tuple[dict[str, bytes], dict[str, dict[str, str]]]:
    """A studio keyring: each person's signing secret, name and role.

    ``{"people": {"ana": {"name": "Ana Ruiz", "role": "compositor",
    "secret_file": "..."}}}`` (or ``"secret"``). Kept on the server, never in
    a workflow or a browser.
    """
    if not path or not os.path.isfile(path):
        return {}, {}
    with open(path, encoding="utf-8") as fh:
        doc = json.load(fh)
    keys: dict[str, bytes] = {}
    names: dict[str, dict[str, str]] = {}
    for user, info in (doc.get("people") or {}).items():
        secret = str(info.get("secret", "") or "")
        if not secret and info.get("secret_file") and os.path.isfile(info["secret_file"]):
            with open(info["secret_file"], encoding="utf-8") as fh:
                secret = fh.read().strip()
        if not secret:
            continue
        key = _derive(secret, b"comfyaudit-sign:" + str(user).encode("utf-8"))
        kid = f"person:{user}:{sha256(key)[:12]}"
        keys[kid] = key
        names[kid] = {"user": str(user), "name": str(info.get("name") or user),
                      "role": str(info.get("role", "") or "")}
    return keys, names


CONFIDENTIALITY_ORDER = ("none", "redact", "encrypt")


def strongest(*modes: str) -> str:
    """The most protective of several confidentiality modes."""
    known = [m for m in modes if m in CONFIDENTIALITY_ORDER]
    return max(known, key=CONFIDENTIALITY_ORDER.index) if known else "none"


def _derive(secret: str, salt: bytes) -> bytes:
    """Stretch a passphrase into a 32-byte key. Stdlib scrypt, fixed salt per use.

    The salt is fixed on purpose: the same studio passphrase has to produce the
    same key on every workstation, and the threat here is tampering with a file,
    not offline cracking of a key nobody has the ciphertext-plaintext pair for.
    """
    return hashlib.scrypt(secret.encode("utf-8"), salt=salt, n=2 ** 14, r=8, p=1,
                          dklen=32)


def encryption_available() -> bool:
    try:
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM  # noqa: F401
    except Exception:  # noqa: BLE001
        return False
    return True


def fingerprint(text: str, keys: Keys) -> str:
    """A stable fingerprint for a sensitive string.

    With a studio key it is an HMAC, so a short prompt or a guessable file path
    cannot be confirmed by hashing candidates - only a key holder can check
    which text was used. Without a key it is a plain SHA-256, which is still
    stable across entries but is no secret for short or guessable text.
    """
    key = keys.enc_key or keys.sign_key
    if key and keys.confidentiality != "none":
        return "hmac:" + hmac.new(key, text.encode("utf-8"), hashlib.sha256).hexdigest()
    return sha256(text)


def _seal(text: str, keys: Keys) -> dict[str, Any]:
    """Protect one sensitive string according to the confidentiality mode."""
    digest = fingerprint(text, keys)
    if keys.confidentiality == "encrypt" and keys.enc_key:
        if not encryption_available():
            # Fail closed: never write the plaintext the studio asked us to hide.
            return {"sha256": digest, "redacted": True,
                    "reason": "encryption requested but the 'cryptography' package is not installed"}
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
        nonce = os.urandom(12)
        blob = AESGCM(keys.enc_key).encrypt(nonce, text.encode("utf-8"), None)
        return {"sha256": digest,
                "enc": "AES-256-GCM",
                "data": base64.b64encode(nonce + blob).decode("ascii")}
    if keys.confidentiality in ("redact", "encrypt"):
        return {"sha256": digest, "redacted": True}
    return {"sha256": digest, "text": text}


def unseal(sealed: dict[str, Any], keys: Keys) -> str | None:
    """The original text, or None if it was redacted or the key is wrong."""
    if "text" in sealed:
        return sealed["text"]
    if sealed.get("enc") == "AES-256-GCM" and keys.enc_key and encryption_available():
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
        raw = base64.b64decode(sealed["data"])
        try:
            return AESGCM(keys.enc_key).decrypt(raw[:12], raw[12:], None).decode("utf-8")
        except Exception:  # noqa: BLE001 - wrong key looks like any other failure
            return None
    return None


