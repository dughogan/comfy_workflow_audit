def empty(name: str = "", project: str = "",
          external_ids: dict[str, str] | None = None) -> dict[str, Any]:
    """A new history. ``external_ids`` ties it to the studio's own tracking -
    the ShotGrid or Sparky entity the asset was born as - so provenance starts
    where the studio says it starts, not where ComfyUI first saw it."""
    return {
        "schema": SCHEMA,
        "shot": {"id": str(uuid.uuid4()), "name": name, "project": project,
                 "started": now(), "external_ids": dict(external_ids or {}),
                 "stage": "sandbox"},
        "entries": [],
    }


def read(data: dict[str, Any]) -> dict[str, Any] | None:
    """The history carried by a workflow document, if it has one."""
    if graph._looks_like_api(data):  # noqa: SLF001
        h = data.get("_comfyaudit_history")
    else:
        h = (data.get("extra") or {}).get(EXTRA_KEY)
    return h if isinstance(h, dict) and h.get("schema") == SCHEMA else None


def write(data: dict[str, Any], history: dict[str, Any]) -> dict[str, Any]:
    """Return a copy of the workflow with the history embedded in it.

    UI-format workflows keep it under ``extra``, which ComfyUI preserves on
    save and copies into every rendered PNG. API-format prompts have no such
    slot - every top-level key is a node - so they get a sidecar instead; see
    ``sidecar_path``.
    """
    out = copy.deepcopy(data)
    if graph._looks_like_api(out):  # noqa: SLF001
        raise ValueError("API-format workflows cannot carry history inline; "
                         "save it as a sidecar with history.save_sidecar()")
    out.setdefault("extra", {})[EXTRA_KEY] = history
    return out


def sidecar_path(workflow_path: str) -> str:
    base, _ = os.path.splitext(workflow_path)
    return base + ".history.json"


def snapshot_of(entries: list[dict[str, Any]], entry: dict[str, Any]) -> dict[str, Any]:
    """The snapshot an entry stands for, following a back-reference if needed.

    A review, an approval or a render of an unchanged graph records the same
    state as the entry before it. Storing that state once and pointing at it
    keeps a shot with hundreds of reviews from growing hundreds of copies; the
    pointer and the snapshot's hash are both covered by the chain.
    """
    if "snapshot" in entry:
        return entry["snapshot"]
    ref = entry.get("snapshot_ref")
    if isinstance(ref, int) and 1 <= ref <= len(entries) and ref < entry.get("seq", 0):
        return snapshot_of(entries, entries[ref - 1])
    return {}


def _entry_hash(entry: dict[str, Any]) -> str:
    body = {k: v for k, v in entry.items() if k not in ("hash", "sig")}
    return sha256(canonical(body))


def _sign(digest: str, keys: Keys) -> str:
    return hmac.new(keys.sign_key, digest.encode("ascii"), hashlib.sha256).hexdigest()


def _output_row(o: Any) -> dict[str, Any]:
    """An output as recorded: a name, and a fingerprint when the file exists.

    The fingerprint is what lets anyone later prove *this* delivered frame came
    from *this* entry - and, paired with the input fingerprints in the same
    snapshot, show what the model changed from the original.
    """
    if isinstance(o, dict):
        return {k: v for k, v in o.items() if v not in (None, "")}
    path = str(o)
    row: dict[str, Any] = {"file": os.path.basename(path)}
    if os.path.isfile(path):
        h = hashlib.sha256()
        with open(path, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                h.update(chunk)
        row["sha256"] = h.hexdigest()
        row["bytes"] = os.path.getsize(path)
    return row


def _protect_output(row: dict[str, Any], keys: Keys) -> dict[str, Any]:
    """Output names come from filename prefixes, which often carry the brief."""
    if keys.confidentiality != "none" and row.get("file"):
        ext = os.path.splitext(row["file"])[1]
        row = {**row, "file": "protected-" + fingerprint(row["file"], keys).split(":")[-1][:12] + ext}
    return row


def append(history: dict[str, Any], data: dict[str, Any], *, event: str = "edited",
           actor: Actor | None = None, note: str = "", outputs: Iterable[str] = (),
           keys: Keys | None = None, force: bool = False,
           data_payload: dict[str, Any] | None = None,
           matcher: licences_mod.LicenceMatcher | None = None) -> dict[str, Any] | None:
    """Add one entry. Returns it, or None when nothing substantive changed.

    An ``edited`` stamp on an unchanged graph is skipped: a save that changed
    nothing would otherwise bury the real history under noise. Every other
    event - a render, a review, an approval - is recorded regardless, because
    the fact that it happened is the point.
    """
    if event not in EVENTS:
        raise ValueError(f"unknown event {event!r}; expected one of {', '.join(EVENTS)}")
    keys = keys or Keys()
    actor = actor or Actor.current()
    entries = history.setdefault("entries", [])
    snap = snapshot(data, keys, matcher)
    prev = entries[-1] if entries else None
    prev_snap = snapshot_of(entries, prev) if prev else None

    if (event == "edited" and prev_snap and not force
            and prev_snap.get("graph_sha256") == snap["graph_sha256"]):
        return None

    if not entries and event == "edited":
        # The first thing a history sees is either a new graph or an existing
        # one being taken under tracking. Calling it an edit would hide that
        # everything before this point is unrecorded.
        event = "imported"

    snap_hash = sha256(canonical(snap))
    changes = diff(prev_snap, snap)
    entry: dict[str, Any] = {
        "seq": len(entries) + 1,
        "at": now(),
        "event": event,
        "actor": actor.as_dict(),
        "note": note,
        "outputs": [_protect_output(_output_row(o), keys) for o in outputs],
        "data": data_payload or {},
        # The shot's identity and external IDs ride inside every entry, so the
        # ShotGrid link is covered by the chain rather than sitting beside it.
        "shot": {k: history.get("shot", {}).get(k) for k in
                 ("id", "name", "project", "external_ids")},
        "snapshot": snap,
        "snapshot_sha256": snap_hash,
        "changes": changes,
        "breakpoints": breakpoints_for(event, changes, note),
        "confidentiality": keys.confidentiality,
        "prev": prev["hash"] if prev else "",
    }
    if prev and prev.get("snapshot_sha256") == snap_hash:
        del entry["snapshot"]
        entry["snapshot_ref"] = prev["seq"] if "snapshot" in prev else prev["snapshot_ref"]
    if keys.sign_key:
        entry["key_id"] = keys.key_id
    entry["hash"] = _entry_hash(entry)
    if keys.sign_key:
        entry["sig"] = _sign(entry["hash"], keys)
    entries.append(entry)
    return entry


@dataclass
class StampResult:
    """What a stamp produced. ``workflow`` is the document to save; for an
    API-format prompt it is unchanged and ``history`` goes in the sidecar."""

    workflow: dict[str, Any]
    history: dict[str, Any]
    entry: dict[str, Any] | None
    sidecar: bool = False


def stamp(data: dict[str, Any], *, event: str = "edited", actor: Actor | None = None,
          note: str = "", outputs: Iterable[Any] = (), keys: Keys | None = None,
          name: str = "", project: str = "", ledger: str = "",
          external_ids: dict[str, str] | None = None,
          data_payload: dict[str, Any] | None = None,
          history: dict[str, Any] | None = None,
          force: bool = False) -> StampResult:
    """One call for callers: read, append, write back, witness. Pure on ``data``.

    ``history`` is for API-format workflows, whose history lives in a sidecar
    the caller has already loaded.
    """
    keys = keys or Keys.from_environment()
    existing = history if history is not None else read(data)
    if existing and existing.get("entries"):
        # Signing a new entry on top of tampering would launder it: the new
        # signature makes a damaged record look freshly vouched for.
        check = verify({}, keys=keys, ledger=ledger, history=existing)
        if check.assurance == "none":
            raise ValueError("this shot's history is damaged and cannot be extended: "
                             f"{check.problems[0]}. Export the provenance record for "
                             "review and start a new history.")
    history = copy.deepcopy(existing) \
        or empty(name=name, project=project, external_ids=external_ids)
    shot = history["shot"]
    if name and not shot.get("name"):
        shot["name"] = name
    if project and not shot.get("project"):
        shot["project"] = project
    for k, v in (external_ids or {}).items():
        shot.setdefault("external_ids", {})[k] = v
    payload = dict(data_payload or {})
    if event == "promoted":
        stage = payload.get("stage", "")
        if stage not in STAGES:
            raise ValueError(f"stage must be one of {', '.join(STAGES)}")
        payload["from"] = shot.get("stage", "sandbox")
    if event == "sourced":
        origin = payload.get("origin", "unknown")
        if origin not in ORIGINS:
            raise ValueError(f"origin must be one of {', '.join(ORIGINS)}")
        if not payload.get("node"):
            raise ValueError("a source declaration names the input node it is about")
    entry = append(history, data, event=event, actor=actor, note=note,
                   outputs=outputs, keys=keys, force=force, data_payload=payload)
    if entry and event == "promoted":
        shot["stage"] = payload["stage"]
    if entry and ledger:
        witness(ledger, history, entry)
    if graph._looks_like_api(data):  # noqa: SLF001
        return StampResult(copy.deepcopy(data), history, entry, sidecar=True)
    return StampResult(write(data, history), history, entry)


# ---------------------------------------------------------------------------
# the ledger: a witness outside the file
# ---------------------------------------------------------------------------

def witness(ledger_path: str, history: dict[str, Any], entry: dict[str, Any]) -> None:
    """Append the new head to an append-only JSONL ledger the studio keeps.

    The chain inside the file proves the entries agree with each other. It
    cannot prove none were dropped from the end, or that the whole history was
    not swapped for a cleaner one. A copy of each head hash kept somewhere the
    workflow does not travel closes both gaps.
    """
    os.makedirs(os.path.dirname(os.path.abspath(ledger_path)), exist_ok=True)
    row = {"shot": history["shot"]["id"], "name": history["shot"].get("name", ""),
           "seq": entry["seq"], "hash": entry["hash"], "at": entry["at"],
           "event": entry["event"], "actor": entry["actor"].get("name", "")}
    with open(ledger_path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(row, sort_keys=True) + "\n")


def _ledger_rows(ledger_path: str, shot_id: str) -> list[dict[str, Any]]:
    rows = []
    with open(ledger_path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except ValueError:
                continue
            if row.get("shot") == shot_id:
                rows.append(row)
    return rows


